# Dictionary

# Creating an empty dictionary
empty_dict = {}
print(empty_dict)

# Creating a dictionary with values
person = {
    'name': 'John',
    'age': 30,
    'city': 'New York'
}
print(person)

# Accessing values using keys

person = {
    'name': 'John',
    'age': 30,
    'city': 'New York'
}
print(person['name'])  # Output: John

# Using get() method (returns None if key not found)
print(person.get('age'))  # Output: 30
print(person.get('country', 'Not Found'))  # Output: Not Found

# Adding a new key-value pair

person = {
    'name': 'John',
    'age': 30,
    'city': 'New York'
}
person['country'] = 'USA'
print(person)

# Updating an existing key
person['age'] = 35
print(person)

# Using pop() – removes key and returns value
person = {
    'name': 'John',
    'age': 30,
    'city': 'New York'
}

age = person.pop('age')
print(age)
print(person)

# Using del – removes key (raises error if key not found)
del person['city']
print(person)

# Using popitem() – removes and returns the last inserted key-value pair
last_item = person.popitem()
print(last_item)
print(person)

# Using clear() – removes all elements
person.clear()
print(person)

person = {'name': 'Alice', 'age': 25}
if 'name' in person:
    print('Name exists')
else:
    print('Name not found')

# Looping through keys
person = {'name': 'Alice', 'age': 25}

for key in person:
    print(key)

# Looping through values
for value in person.values():
    print(value)

# Looping through key-value pairs
for key, value in person.items():
    print(f'{key}: {value}')

person = {'name': 'Alice', 'age': 25}

# copy() – creates a shallow copy
person_copy = person.copy()
print(person_copy)

# keys() – returns all keys
print(person.keys())

# values() – returns all values
print(person.values())

# items() – returns key-value pairs as tuples
print(person.items())

